#!/usr/bin/env python3
"""Writes cfg/war3source.cfg: every engine setting (CreateConVar) of the CS:S plugins, commented out with its default."""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = open(os.path.join(ROOT, 'tools', 'build.sh')).read()
OTHER_GAMES = set(re.search(r'OTHER_GAMES="([^"]*)"', BUILD).group(1).split())
CVAR = re.compile(r'CreateConVar\s*\(\s*"([^"]+)"\s*,\s*"([^"]*)"\s*(?:,\s*"((?:[^"\\]|\\.)*)")?')

out = ['// War3Source settings, executed at every map start (war3_load_war3source_cfg_every_map).',
       '// Every setting is listed with its default value, commented out: remove the // in front of a line to change it.',
       '// Generated by tools/gen_cfg.py from the plugin sources.', '']
seen = set()
for path in sorted(glob.glob(os.path.join(ROOT, 'addons/sourcemod/scripting/*.sp'))):
    name = os.path.basename(path)[:-3]
    if name in OTHER_GAMES:
        continue
    rows = []
    for m in CVAR.finditer(open(path, encoding='latin1').read()):
        cvar, value, desc = m.group(1), m.group(2), (m.group(3) or '').replace('\\"', '"')
        if cvar in seen or not cvar.startswith(('war3_', 'w3_')) or cvar.endswith('_version'):
            continue
        seen.add(cvar)
        rows.append(f'//{cvar} "{value}"' + (f'\t\t// {desc}' if desc else ''))
    if rows:
        out.append('// --- ' + name.replace('War3Source_', '').replace('_', ' '))
        out += rows + ['']
with open(os.path.join(ROOT, 'cfg', 'war3source.cfg'), 'w') as f:
    f.write('\n'.join(out))
print(f'{len(seen)} settings -> cfg/war3source.cfg')
